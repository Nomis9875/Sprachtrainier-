async function fromCacheOrNetwork(path, request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(path);
  if (!cached) return fetch(request);
  const range = request.headers.get("range");
  return range ? partial(cached, range) : cached;
}

/** Antwort auf eine Range-Anfrage aus der gecachten Datei ("bytes=start-end", auch offen: "bytes=start-"). */
async function partial(response, range) {
  const data = await response.arrayBuffer();
  const match = /^bytes=(\d*)-(\d*)$/.exec(range.trim());
  const size = data.byteLength;
  if (!match) return new Response(null, { status: 416, headers: { "Content-Range": `bytes */${size}` } });
  let start = match[1] === "" ? size - Number(match[2]) : Number(match[1]);
  let end = match[1] !== "" && match[2] !== "" ? Number(match[2]) : size - 1;
  start = Math.max(0, start);
  end = Math.min(size - 1, end);
  if (start > end) return new Response(null, { status: 416, headers: { "Content-Range": `bytes */${size}` } });
  return new Response(data.slice(start, end + 1), {
    status: 206,
    headers: {
      "Content-Type": response.headers.get("Content-Type") ?? "application/octet-stream",
      "Content-Range": `bytes ${start}-${end}/${size}`,
      "Content-Length": String(end - start + 1),
      "Accept-Ranges": "bytes",
    },
  });
}
